fun lessonById(id: String): Lesson? = LESSONS.firstOrNull { it.id == id }

/**
 * درس اليوم: أول درس ما انقرى، بشرط ما نسبق التقويم (درس جديد واحد باليوم).
 * يرجع null إذا قرا درس اليوم أو خلص الرحلة.
 */
fun lessonForToday(read: List<String>, startDate: String, today: String, readToday: Boolean): Lesson? {
    if (readToday) return null
    val next = LESSONS.firstOrNull { it.id !in read } ?: return null
    val unlocked = (daysBetween(startDate, today) + 1).coerceAtLeast(1)
    return if (LESSONS.indexOf(next) < unlocked) next else null
}
